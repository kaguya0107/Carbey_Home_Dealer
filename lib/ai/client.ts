/**
 * ⑮ クレーム対応の「判定の根拠」ブロック。現行の利用規約・別添（各種料金表）を注入し、
 * できる／できない判断の基準にさせる。規約が読めない場合はその旨を明示させる。
 */
function renderTermsBasis(termsContext: string | null | undefined): string {
  const t = termsContext?.trim()
  if (!t) {
    return `

## 判定の根拠（規約・契約・各種料金表）

現在、参照できる利用規約が読み込めていません。この場合、可否判断は一般論に留め、必ず
「実際の可否は現行規約・契約書のご確認が必要です」と明示してください（規約を根拠に断定しないこと）。`
  }
  return `

## 判定の根拠（規約・契約・各種料金表）

以下はカーベイの現行の利用規約および別添（各種料金表・規定）です。クレーム対応の「できる／できない」は、
**必ずこの内容を基準に判断し、該当する条項・項目を引用**してください。ここに書かれていない事項は
「規約に明記なし＝要確認」とし、憶測で可否を断定しないこと。

<規約・料金表>
${t}
</規約・料金表>`
}

